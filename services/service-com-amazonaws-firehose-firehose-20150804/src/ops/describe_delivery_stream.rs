/// The deprecated `DestinationDescription$S3DestinationDescription` mirror of an Amazon S3
/// destination, projected from the description Firehose renders for it.
///
/// The member predates `ExtendedS3DestinationDescription` and reports the same destination
/// under the shape the deprecated spelling models: the subset of members the two
/// descriptions share, already carrying this destination's EFFECTIVE configuration (the
/// supplied values with every documented default materialised). A destination that IS an
/// Amazon S3 destination is reported through both members, so a client reading either one
/// sees the same bucket, role, buffering, compression, encryption and logging.
fn legacy_s3_mirror(extended: &ExtendedS3DestinationDescription) -> S3DestinationDescription {
    S3DestinationDescription {
        role_arn: extended.role_arn.clone(),
        bucket_arn: extended.bucket_arn.clone(),
        prefix: extended.prefix.clone(),
        error_output_prefix: extended.error_output_prefix.clone(),
        buffering_hints: extended.buffering_hints.clone(),
        compression_format: extended.compression_format.clone(),
        encryption_configuration: extended.encryption_configuration.clone(),
        cloud_watch_logging_options: extended.cloud_watch_logging_options.clone(),
    }
}

/// The S3 description for an `S3DestinationConfiguration`, applying the documented
/// defaults for the three members the description requires but the configuration leaves
/// optional.
fn s3_description(config: &S3DestinationConfiguration) -> S3DestinationDescription {
    S3DestinationDescription {
        role_arn: config.role_arn.clone(),
        bucket_arn: config.bucket_arn.clone(),
        prefix: config.prefix.clone(),
        error_output_prefix: config.error_output_prefix.clone(),
        buffering_hints: buffering_hints(config.buffering_hints.as_ref()),
        compression_format: compression_format(config.compression_format.as_ref()),
        encryption_configuration: encryption_configuration(
            config.encryption_configuration.as_ref(),
        ),
        cloud_watch_logging_options: logging(&config.cloud_watch_logging_options),
    }
}

fn compression_format(format: Option<&String>) -> String {
    format.cloned().unwrap_or_else(|| DEFAULT_COMPRESSION_FORMAT.to_string())
}

/// The `S3BackupMode` a destination description reports: the one the configuration
/// supplied, else the `default` its own documentation gives that destination kind.
///
/// Firehose materialises a documented default into the description it reports rather than
/// leaving the member unset, so a client comparing desired against actual configuration
/// (or round-tripping a description back into `UpdateDestination`) reads an explicit
/// value. Only the destination kinds whose model documents a default get one here — for
/// the rest there is no value to materialise.
fn s3_backup_mode(mode: Option<&String>, default: &str) -> String {
    mode.cloned().unwrap_or_else(|| default.to_string())
}

/// "The encryption configuration. If no value is specified, the default is no
/// encryption."
fn encryption_configuration(config: Option<&EncryptionConfiguration>) -> EncryptionConfiguration {
    config.cloned().unwrap_or_else(|| EncryptionConfiguration {
        no_encryption_config: Some("NoEncryption".to_string()),
        kms_encryption_config: None,
    })
}
